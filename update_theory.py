def update():
    with app.app_context():
        updated = 0
        not_found = []

        for module_title, new_html in NEW_THEORY.items():
            module = Module.query.filter_by(title=module_title).first()
            if not module:
                not_found.append(module_title)
                continue

            theory_level = next(
                (lv for lv in module.levels if lv.type == 'theory'), None
            )
            if not theory_level:
                not_found.append(f'{module_title} (no theory level)')
                continue

            theory_level.theory_content = new_html
            updated += 1

        db.session.commit()
        print(f'Updated {updated} theory articles.')
        if not_found:
            print(f'Not found: {not_found}')


if __name__ == '__main__':
    update()
