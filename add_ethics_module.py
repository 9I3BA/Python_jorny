def run():
    with app.app_context():
        existing = Module.query.filter_by(title='Этика кода').first()
        if existing:
            print('Модуль «Этика кода» уже существует, пропускаем.')
            return

        next_order = db.session.query(db.func.max(Module.order)).scalar()
        next_order = (next_order or 0) + 1

        module = Module(
            title='Этика кода',
            icon='📐',
            color='#7C3AED',
            description='Как писать код красиво, честно и ответственно',
            map_x=500, map_y=200,
            order=next_order,
        )
        db.session.add(module)
        db.session.flush()

        for idx, lv in enumerate(ETHICS_LEVELS):
            level = Level(
                module_id=module.id,
                order=idx,
                title=lv['title'],
                type=lv['type'],
                xp_reward=lv['xp_reward'],
                theory_content=lv['theory_content'],
                task_description=lv['task_description'],
                expected_output=lv['expected_output'],
                blocks_config=lv['blocks_config'],
                hint=lv['hint'],
            )
            db.session.add(level)

        db.session.commit()
        print(f'Добавлен модуль «Этика кода» (order={next_order}) с {len(ETHICS_LEVELS)} уровнями.')


if __name__ == '__main__':
    run()
