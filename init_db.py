def init():
    with app.app_context():
        db.drop_all()
        db.create_all()

        # Demo users
        admin = User(username='admin', email='admin@pylearn.ru',
                     password_hash=generate_password_hash('admin123'), role='admin')
        teacher = User(username='teacher1', email='teacher@pylearn.ru',
                       password_hash=generate_password_hash('teacher123'), role='teacher')
        student = User(username='student1', email='student@pylearn.ru',
                       password_hash=generate_password_hash('student123'), role='student')
        parent = User(username='parent1', email='parent@pylearn.ru',
                      password_hash=generate_password_hash('parent123'), role='parent')
        db.session.add_all([admin, teacher, student, parent])
        db.session.flush()
        student.parent_id = parent.id

        # Modules and levels
        for mod_idx, mod_data in enumerate(MODULES):
            m = Module(
                title=mod_data['title'],
                description=mod_data['description'],
                order=mod_idx,
                icon=mod_data['icon'],
                color=mod_data['color'],
                map_x=mod_data['map_x'],
                map_y=mod_data['map_y'],
            )
            db.session.add(m)
            db.session.flush()
            for lv_idx, lv_data in enumerate(mod_data['levels']):
                lv = Level(
                    module_id=m.id,
                    title=lv_data['title'],
                    type=lv_data['type'],
                    order=lv_idx + 1,
                    xp_reward=lv_data['xp_reward'],
                    theory_content=lv_data['theory_content'],
                    task_description=lv_data['task_description'],
                    expected_output=lv_data.get('expected_output') or '',
                    blocks_config=lv_data.get('blocks_config', '{}'),
                    hint=lv_data.get('hint', ''),
                )
                db.session.add(lv)

        # Achievements
        for ach_data in ACHIEVEMENTS:
            db.session.add(Achievement(**ach_data))

        # Cases and avatars
        for case_data in CASES:
            c = Case(
                name=case_data['name'],
                description=case_data['description'],
                price=case_data['price'],
                emoji=case_data['emoji'],
                color=case_data['color'],
            )
            db.session.add(c)
            db.session.flush()
            for av_data in case_data['avatars']:
                db.session.add(Avatar(case_id=c.id, **av_data))

        for av_data in FREE_AVATARS:
            db.session.add(Avatar(**av_data))

        # Demo group
        g = Group(name='Группа Python-1', teacher_id=teacher.id)
        db.session.add(g)
        db.session.flush()
        db.session.add(GroupMember(group_id=g.id, user_id=student.id))

        db.session.commit()

        total_levels = sum(len(m['levels']) for m in MODULES)
        print(f'DB initialized! {len(MODULES)} modules, {total_levels} levels.')
        print('Logins: admin/admin123 | teacher1/teacher123 | student1/student123 | parent1/parent123')


if __name__ == '__main__':
    init()
